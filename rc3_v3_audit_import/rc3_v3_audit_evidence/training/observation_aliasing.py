"""Construct two valid abstract F/D problems with identical v3 observations.

The two instances have the SAME task coverage, candidate poses and current-route
shortest distances. Only the unused candidate's branch travel distance changes.
Both distance matrices are tree shortest-path metrics. This is an information
counterexample in the declared abstract model, not a measured test-data collision
or a claim that these exact tables were generated by the current scene generator.
"""
import argparse
import json
from pathlib import Path
from types import SimpleNamespace
import sys
import numpy as np

def problem(branch_length):
    # Graph: 0--1--2--3, all edges length one; unused candidate4 branches at2.
    base=np.arange(4,dtype=float)
    costs=np.zeros((5,5),float)
    costs[:4,:4]=np.abs(base[:,None]-base[None,:])
    costs[4,:4]=costs[:4,4]=np.abs(base-2)+branch_length
    cover=np.zeros((3,4,2),bool)
    for i in range(3):cover[i,i,0]=True
    cover[[0,1],3,0]=True
    return SimpleNamespace(F=cover,penalty=.75,nav={'costs':costs},
        scene={'x_lines':[0.,12.],'y_lines':[0.,1.],
            'candidates':[{'x':1.,'y':0.},{'x':2.,'y':0.},
                          {'x':3.,'y':0.},{'x':2.,'y':.1}]})


def run(source_root=None):
    source=Path(source_root if source_root is not None else Path.cwd()).expanduser().resolve()
    if not (source/'rc3_v3').is_dir():
        raise ValueError('--source-root must contain the rc3_v3 directory')
    sys.path.insert(0,str(source))
    from rc3_v3.environment import Env
    from rc3_improve.repair import repair_window
    from rc3_fast.solver import route_objective
    a,b=problem(.1),problem(10.)
    envs=[Env(p,8,[0,1,2,3,0]) for p in [a,b]]
    observations=[e.observe() for e in envs]
    gains=[];checks=[]
    for p,e in zip([a,b],envs):
        gains.append([route_objective(p,e.route)-route_objective(p,repair_window(p,e.route,w)) for w in e.windows])
        d=p.nav['costs']
        check=dict(finite=bool(np.isfinite(d).all()),nonnegative=bool((d>=0).all()),
            symmetric=bool(np.array_equal(d,d.T)),zero_diagonal=bool((np.diag(d)==0).all()),
            triangle_inequality=bool(np.all(d[:,None,:] <= d[:,:,None]+d[None,:,:]+1e-9)))
        assert all(check.values())
        checks.append(check)
    result=dict(scope=__doc__.strip(),same_all_observed_features=bool(np.array_equal(observations[0][0],observations[1][0])),
        same_masks=bool(np.array_equal(observations[0][1],observations[1][1])),
        same_candidate_poses=a.scene['candidates']==b.scene['candidates'],same_F=bool(np.array_equal(a.F,b.F)),
        route=[0,1,2,3,0],reference_objective=8.25,
        near_branch_length=.1,far_branch_length=10.,near_window_gains=gains[0],far_window_gains=gains[1],
        opposite_true_stop_labels=max(gains[0])>1e-8 and max(gains[1])<=1e-8,distance_checks=checks,
        observations=observations[0][0].tolist(),distances_near=a.nav['costs'].tolist(),distances_far=b.nav['costs'].tolist())
    assert result['same_all_observed_features'] and result['same_masks'] and result['opposite_true_stop_labels']
    return result


if __name__=='__main__':
    parser=argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--source-root',type=Path,default=Path.cwd(),
        help='Extracted original project root containing rc3_v3, rc3_improve and rc3_fast.')
    parser.add_argument('--output-dir',type=Path,default=Path.cwd()/'v3_training_audit')
    args=parser.parse_args()
    result=run(args.source_root)
    directory=args.output_dir.expanduser().resolve();directory.mkdir(parents=True,exist_ok=True)
    output=directory/'observation_aliasing.json';output.write_text(json.dumps(result,ensure_ascii=False,indent=2))
    print(json.dumps({k:v for k,v in result.items() if k not in ['observations','distances_near','distances_far']},ensure_ascii=False,indent=2))
