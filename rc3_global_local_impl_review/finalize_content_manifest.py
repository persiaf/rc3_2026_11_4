"""Compose this review manifest using already verified frozen bytes plus new hashes.

Run tools/verify_project_archive.py afterwards for an independent full pass.
No semantic project imports, scientific calls, Git mutations or network.
"""
import hashlib
import json
from pathlib import Path
import subprocess
import time

ROOT = Path(__file__).resolve().parents[1]
HERE = Path(__file__).resolve().parent
BASE = '057830d584b6c71c79ef5118087c681c98135fe2'


def digest(p):
    h = hashlib.sha256()
    with p.open('rb') as stream:
        for chunk in iter(lambda: stream.read(4 * 1024 * 1024), b''):
            h.update(chunk)
    return {'sha256': h.hexdigest(), 'bytes': p.stat().st_size}


def main():
    start = time.perf_counter()
    base = json.loads(subprocess.check_output(['git', 'show', BASE + ':project_management/GIT_MANIFEST.json'], cwd=ROOT))
    proof = json.loads((HERE / 'FROZEN_BYTE_CHECK.json').read_text(encoding='utf8'))
    assert proof['base'] == BASE and proof['all_frozen_scientific_bytes_passed']
    assert proof['files_checked'] == len(base['files'])
    audit = json.loads((HERE / 'PREPARATION_AUDIT.json').read_text(encoding='utf8'))
    assert audit['status'] == 'PASS_FINAL'
    archive_receipt = HERE / 'ARCHIVE_VERIFICATION.json'
    if archive_receipt.exists():
        raise RuntimeError('Composition receipt exists; review revisions explicitly before repeating')
    records = dict(base['files'])
    for name in ['AGENTS.md', 'README.md', 'PROJECT_VERSION.json']:
        records[name] = digest(ROOT / name)
    new_files = sorted(p for p in HERE.rglob('*') if p.is_file())
    for p in new_files:
        if p.is_symlink() or not p.resolve().is_relative_to(HERE):
            raise ValueError(p)
        if '__pycache__' in p.parts or p.suffix == '.pyc':
            raise ValueError('Unexpected generated bytecode')
        records[p.relative_to(ROOT).as_posix()] = digest(p)
    receipt = {
      'schema': 'rc3-preflight-content-composition-receipt-v1',
      'status': 'CONTENT_COMPOSITION_PASS_FINAL_FULL_PASS_RECORDED_EXTERNALLY',
      'scope': 'Old scientific bytes verified in FROZEN_BYTE_CHECK; three maintenance files and every new preparation file freshly hashed here. This receipt is then included in the manifest. A separate full standard verifier runs after composition.',
      'base': BASE, 'base_files_checked': proof['files_checked'],
      'base_bytes_checked': proof['bytes_checked'], 'base_byte_verification_wall_s': proof['wall_s'],
      'old_scientific_file_failures': proof['scientific_file_failures'],
      'new_files_hashed_before_this_receipt': len(new_files),
      'composition_wall_s_before_receipt_write': time.perf_counter() - start,
      'independent_scientific_preparation_review': audit['status'],
      'full_verifier_command': '.\\rc3_learning\\.venv\\Scripts\\python.exe -B tools/verify_project_archive.py',
      'final_verifier_and_postcommit_receipt': 'C:/Users/Administrator/.codex/visualizations/2026/11/05/01a1a94c-0029-7ce0-8779-0aeba8eaddc1/global_local_preflight_git_receipt.json',
      'cycle_policy': 'Final verifier stdout and actual commit SHA are external metadata; scientific files and this composition receipt are covered by the committed content manifest.',
      'excluded_unrelated_user_files': 'Untracked Office lock file is not part of the project manifest or staged changes.',
      'new_scientific_calls': 0
    }
    archive_receipt.write_text(json.dumps(receipt, ensure_ascii=False, indent=2) + '\n', encoding='utf8')
    records[archive_receipt.relative_to(ROOT).as_posix()] = digest(archive_receipt)
    base['files'] = dict(sorted(records.items()))
    base['version'] = json.loads((ROOT / 'PROJECT_VERSION.json').read_text(encoding='utf8'))['version']
    base['file_count'] = len(records)
    base['total_bytes'] = sum(v['bytes'] for v in records.values())
    base['scope'] = 'Original LFS working-tree bytes; historical scientific evidence preserved. Current preflight engineering checks separately accounted, no optimizer training or S3 target evaluation.'
    base['preflight_extension'] = {'base': BASE, 'branch': 'codex/global-local-preflight',
      'report': 'rc3_global_local_impl_review/IMPLEMENTATION_REVIEW.md',
      'formal_training_decision': 'REVISE', 'new_optimizer_updates': 0,
      'S3_target_queries': 0, 'new_trained_weights': 0, 'v3_activated': False,
      'pushed': False, 'main_merged': False, 'unrelated_user_files_excluded': True}
    (ROOT / 'project_management/GIT_MANIFEST.json').write_text(json.dumps(base, ensure_ascii=False, indent=2) + '\n', encoding='utf8')
    print(json.dumps({'files': len(records), 'bytes': base['total_bytes'], 'new_preparation_files': len(new_files) + 1, 'next': 'Run full verifier, commit explicit scope, record actual SHA externally.'}))


if __name__ == '__main__':
    main()
